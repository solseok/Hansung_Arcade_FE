package hansung.arcade.ingame.entity;

/**
 * 물풍선 싸움에서 플레이어가 놓인 상태. 보통 → 갇힘 → (구출되면) 빠져나오는 중 → 보통, 또는 갇힘 → 죽는 중 → 사라짐으로 흐른다.
 */
public enum PlayerState {
    /** 돌아다니며 물풍선을 놓을 수 있다 */
    NORMAL,
    /** 물줄기에 맞아 물풍선에 갇혔다. 아주 느리게만 움직이고 물풍선을 놓지 못한다 */
    TRAPPED,
    /** 갇혔던 물풍선이 깨져 나오는 중이다 (같은 편이 구했을 때, 이후 바늘 아이템). 연출이 끝날 때까지 움직이지 못한다 */
    ESCAPING,
    /** 쓰러진 채 위로 솟았다 떨어진 뒤 깜빡이는 중이다. 이미 탈락했다 */
    DYING,
    /** 연출까지 끝나 맵에서 사라졌다 */
    GONE
}
